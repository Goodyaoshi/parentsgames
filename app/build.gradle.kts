// Assinatura de release: lê de keystore.properties na raiz (NÃO versionado).
// Veja keystore.properties.example. Sem o arquivo, o release cai no debug signing
// (útil para a CI), mas o AAB da Play Store exige o keystore de upload.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}

